// Both icons render and CSS shows the right one, so the button never disagrees with the page.
export default function ThemeToggle() {
  const toggle = () => {
    const next = !document.documentElement.classList.contains("dark");
    document.documentElement.classList.toggle("dark", next);
    try {
      localStorage.setItem("theme", next ? "dark" : "light");
    } catch {}
  };

  return (
    <button type="button" onClick={toggle} className="theme-toggle" aria-label="Toggle light and dark theme">
      <span className="icon-sun"><SunIcon /></span>
      <span className="icon-moon"><MoonIcon /></span>
    </button>
  );
}
